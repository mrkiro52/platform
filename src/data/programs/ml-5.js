const curve = (fn, a, b, n = 160) => Array.from({ length: n + 1 }, (_, i) => { const x = a + ((b - a) * i) / n; return [x, fn(x)] })
const parabola = w => (w - 3) ** 2

// Траектория спуска по f(w) = (w − 3)², старт w = 0
function path1d(lr, steps) {
  const pts = []
  let w = 0
  for (let t = 0; t <= steps; t++) { pts.push([w, parabola(w)]); w -= lr * 2 * (w - 3) }
  return pts
}

// Значение функции потерь по итерациям для разных шагов (обрезаем то, что улетело за график)
function lossCurve(lr, steps = 20, cap = 10) {
  const pts = []
  let w = 0
  for (let t = 0; t <= steps; t++) {
    const v = parabola(w)
    if (v > cap) break
    pts.push([t, v])
    w -= lr * 2 * (w - 3)
  }
  return pts
}

// Линии уровня эллиптической «долины» f = a·x² + b·y²
function ellipse(level, a, b, n = 120) {
  return Array.from({ length: n + 1 }, (_, i) => {
    const t = (2 * Math.PI * i) / n
    return [Math.sqrt(level / a) * Math.cos(t), Math.sqrt(level / b) * Math.sin(t)]
  })
}
// Путь градиентного спуска по f = a·x² + b·y²
function path2d(a, b, lr, start, steps) {
  const pts = []
  let [x, y] = start
  for (let t = 0; t <= steps; t++) { pts.push([x, y]); x -= lr * 2 * a * x; y -= lr * 2 * b * y }
  return pts
}
// Momentum по той же функции
function pathMomentum(a, b, lr, beta, start, steps) {
  const pts = []
  let [x, y] = start
  let vx = 0, vy = 0
  for (let t = 0; t <= steps; t++) {
    pts.push([x, y])
    vx = beta * vx + 2 * a * x; vy = beta * vy + 2 * b * y
    x -= lr * vx; y -= lr * vy
  }
  return pts
}

