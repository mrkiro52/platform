// ── Функции для точек графиков ──────────────────────────────────────────────
const curve = (fn, a, b, n = 160) => Array.from({ length: n + 1 }, (_, i) => { const x = a + ((b - a) * i) / n; return [x, fn(x)] })
const normal = (mu, sd) => x => Math.exp(-((x - mu) ** 2) / (2 * sd * sd)) / (sd * Math.sqrt(2 * Math.PI))
const logFact = k => { let s = 0; for (let i = 2; i <= k; i++) s += Math.log(i); return s }
const binom = (n, p) => k => Math.exp(logFact(n) - logFact(k) - logFact(n - k) + k * Math.log(p) + (n - k) * Math.log(1 - p))
const poisson = l => k => Math.exp(k * Math.log(l) - l - logFact(k))
const expo = l => x => (x < 0 ? 0 : l * Math.exp(-l * x))
const lognormal = (mu, s) => x => (x <= 0 ? 0 : Math.exp(-((Math.log(x) - mu) ** 2) / (2 * s * s)) / (x * s * Math.sqrt(2 * Math.PI)))
// Среднее n экспоненциальных величин со средним 1 распределено как Gamma(n, n)
const meanOfExp = n => x => (x <= 0 ? 0 : Math.exp(n * Math.log(n) + (n - 1) * Math.log(x) - n * x - logFact(n - 1)))

// Детерминированный генератор случайных чисел — графики одинаковы при каждой загрузке
function rng(seed) {
  let a = seed >>> 0
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
}
function gauss(rand) { return Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand()) }

// Закон больших чисел: накопленная конверсия трёх потоков посетителей с истинной конверсией 5%
const llnPaths = [3, 8, 21].map(seed => {
  const rand = rng(seed)
  let hits = 0
  const pts = []
  for (let i = 1; i <= 3000; i++) {
    if (rand() < 0.05) hits++
    if (i >= 20 && (i < 200 ? i % 5 === 0 : i % 25 === 0)) pts.push([i, (100 * hits) / i])
  }
  return pts
})

