const ciSamples = (() => {
  const rand = rng(17)
  return Array.from({ length: 20 }, (_, i) => {
    const xs = Array.from({ length: 100 }, () => 12 + 8 * gauss(rand))
    const m = xs.reduce((s, v) => s + v, 0) / xs.length
    const sd = Math.sqrt(xs.reduce((s, v) => s + (v - m) ** 2, 0) / (xs.length - 1))
    const h = 1.96 * sd / Math.sqrt(xs.length)
    return { y: 20 - i, m, from: m - h, to: m + h }
  })
})()

