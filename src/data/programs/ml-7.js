// Регрессия kNN: среднее (или взвешенное среднее) ответов k соседей по оси x
function knnRegCurve(k, weighted = false, x0 = 0, x1 = 10, n = 500) {
  const pts = []
  for (let i = 0; i <= n; i++) {
    const x = x0 + ((x1 - x0) * i) / n
    const nn = [...REG].sort((a, b) => Math.abs(a[0] - x) - Math.abs(b[0] - x)).slice(0, k)
    if (!weighted) {
      pts.push([x, nn.reduce((s, p) => s + p[1], 0) / k])
    } else {
      const w = nn.map(p => 1 / (Math.abs(p[0] - x) + 1e-3))
      pts.push([x, nn.reduce((s, p, j) => s + w[j] * p[1], 0) / w.reduce((a, b) => a + b, 0)])
    }
  }
  return pts
}

// Единичные «шары» разных метрик: |x|^p + |y|^p = 1
const unitBall = p => Array.from({ length: 361 }, (_, i) => {
  const t = (i / 360) * 2 * Math.PI
  const c = Math.cos(t), s = Math.sin(t)
  if (p === Infinity) { const m = Math.max(Math.abs(c), Math.abs(s)); return [c / m, s / m] }
  const r = (Math.abs(c) ** p + Math.abs(s) ** p) ** (-1 / p)
  return [r * c, r * s]
})

// KD-дерево глубины 3 на 12 точках: вертикальные и горизонтальные разрезы
const KD_PTS = [[1.0, 1.2], [1.6, 4.4], [2.3, 2.6], [2.9, 5.6], [3.6, 1.0], [4.1, 3.4], [5.2, 5.1], [5.9, 2.2], [6.6, 4.0], [7.2, 1.4], [7.9, 5.4], [8.6, 3.0]]
function kdLines(pts, box, depth, out) {
  if (pts.length <= 1 || depth > 2) return out
  const axis = depth % 2
  const sorted = [...pts].sort((a, b) => a[axis] - b[axis])
  const m = Math.floor(sorted.length / 2)
  const cut = (sorted[m - 1][axis] + sorted[m][axis]) / 2
  const [x0, y0, x1, y1] = box
  out.push({ line: axis === 0 ? [[cut, y0], [cut, y1]] : [[x0, cut], [x1, cut]], depth })
  kdLines(sorted.slice(0, m), axis === 0 ? [x0, y0, cut, y1] : [x0, y0, x1, cut], depth + 1, out)
  kdLines(sorted.slice(m), axis === 0 ? [cut, y0, x1, y1] : [x0, cut, x1, y1], depth + 1, out)
  return out
}
