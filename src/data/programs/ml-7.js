// Карта решений kNN: клетки сетки с шагом step, цвет — класс большинства среди k соседей
function decisionCells(k, step = 0.2, x0 = -0.5, x1 = 9.7, y0 = 0.3, y1 = 7.1) {
  const cells = []
  for (let x = x0 + step / 2; x < x1; x += step) {
    for (let y = y0 + step / 2; y < y1; y += step) {
      const votes = nearest(MOONS, [x, y], k).reduce((s, p) => s + p[2], 0)
      cells.push([+x.toFixed(3), +y.toFixed(3), votes * 2 > k ? 1 : 0])
    }
  }
  return cells
}

