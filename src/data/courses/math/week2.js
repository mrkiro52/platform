const fact = n => (n <= 1 ? 1 : n * fact(n - 1))
const comb = (n, k) => fact(n) / (fact(k) * fact(n - k))
const normal = (x, mu = 0, s = 1) => Math.exp(-((x - mu) ** 2) / (2 * s * s)) / (s * Math.sqrt(2 * Math.PI))

// Траектория градиентного спуска для f(x) = x² из точки x0
const gdPath = (x0, lr, steps) => {
  const pts = [[x0, x0 * x0]]
  let x = x0
  for (let i = 0; i < steps; i++) { x -= lr * 2 * x; pts.push([+x.toFixed(4), +(x * x).toFixed(4)]) }
  return pts
}

