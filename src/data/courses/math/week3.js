// Точное распределение суммы n бросков кости — свёртка; отсюда распределение среднего
function diceMeanPmf(n) {
  let dist = [1]
  for (let i = 0; i < n; i++) {
    const next = Array(dist.length + 6).fill(0)
    dist.forEach((pr, s) => { for (let f = 1; f <= 6; f++) next[s + f] += pr / 6 })
    dist = next
  }
  return dist.map((pr, s) => [s / n, pr]).filter(([, pr]) => pr > 0)
}

