export default function July23SecurityInterviewTheory() {
  return (
    <div className="theory-container">
      <section className="theory-section">
        <h1 className="theory-title">Вопросы с собеседования: Кибербезопасность</h1>
        <p className="theory-subtitle">Трек: Кибербезопасность</p>
        <p className="theory-date">23 июля 2026</p>
        <p>
          Тренировка на самых популярных вопросах для собеседований на позиции в сфере информационной
          безопасности. Первый блок — базовые понятия и виды атак. Второй блок — защита, шифрование и практика
          пентеста. Формат — вопрос и развёрнутый ответ.
        </p>
      </section>

      <section className="theory-section">
        <Section title="Часть 1. Базовые понятия и виды атак" />

        <QA n={1} q="Что такое кибербезопасность?">
          Область знаний и практик, направленных на защиту компьютерных систем, сетей и данных от
          несанкционированного доступа, повреждения или кражи. Включает как технические меры (шифрование,
          firewall), так и организационные (политики доступа, обучение сотрудников).
        </QA>

        <QA n={2} q="Что такое триада CIA?">
          Три базовых свойства защищённой информации: Confidentiality (конфиденциальность — доступ только у тех,
          кому положено), Integrity (целостность — данные не изменены незаметно и без разрешения), Availability
          (доступность — данные и системы доступны легитимным пользователям, когда это нужно).
        </QA>

        <QA n={3} q="В чём разница между уязвимостью, эксплойтом и угрозой?">
          Уязвимость — слабое место в системе (ошибка в коде, неверная настройка). Эксплойт — конкретный код или
          приём, который использует эту уязвимость для атаки. Угроза — потенциальный источник вреда (человек,
          программа, событие), который может воспользоваться уязвимостью через эксплойт.
        </QA>

        <QA n={4} q="Что такое фишинг?">
          Заманивание жертвы на поддельный ресурс или заставление её выполнить действие (перейти по ссылке,
          открыть вложение), выдавая себя за доверенный источник, чтобы выманить логин, пароль или другие
          конфиденциальные данные.
        </QA>

        <QA n={5} q="Что такое SQL-инъекция?">
          Атака, при которой злоумышленник вставляет вредоносный SQL-код во входные данные формы или запроса, и
          если приложение не экранирует пользовательский ввод, этот код выполняется базой данных как часть
          «легитимного» запроса — позволяя красть или изменять данные.
        </QA>

        <QA n={6} q="Что такое XSS (межсайтовый скриптинг)?">
          Уязвимость, при которой злоумышленник внедряет вредоносный JavaScript-код на страницу, который затем
          выполняется в браузере других пользователей, посещающих эту страницу — позволяя красть cookies, токены
          сессии или выполнять действия от имени жертвы.
        </QA>

        <QA n={7} q="Что такое CSRF (межсайтовая подделка запроса)?">
          Атака, при которой пользователя, уже авторизованного на сайте, обманом заставляют выполнить нежелательное
          действие (например, перевод денег) через скрытый запрос с другого сайта — браузер автоматически
          подставляет cookies сессии, и сервер думает, что запрос легитимен.
        </QA>

        <QA n={8} q="Что такое DDoS-атака?">
          Distributed Denial of Service — атака, при которой множество устройств (часто заражённых, объединённых
          в ботнет) одновременно отправляют огромное количество запросов серверу, перегружая его так, что он не
          может обслуживать легитимных пользователей.
        </QA>

        <QA n={9} q="Что такое социальная инженерия?">
          Манипуляция человеком (а не технической системой), чтобы заставить его раскрыть информацию или выполнить
          нужное атакующему действие — через давление на эмоции: срочность, страх, авторитет, доверие.
        </QA>

        <QA n={10} q="Что такое zero-day уязвимость?">
          Уязвимость, о которой ещё не знает производитель ПО (и поэтому нет патча/исправления) — либо
          злоумышленники узнали о ней раньше разработчиков и уже используют её на момент обнаружения («ноль дней»
          на исправление).
        </QA>

        <QA n={11} q="Что такое ransomware (программа-вымогатель)?">
          Вредоносная программа, которая шифрует файлы жертвы или блокирует доступ к системе, а затем требует
          выкуп (обычно в криптовалюте) за восстановление доступа.
        </QA>

        <QA n={12} q="Что такое атака «человек посередине» (Man-in-the-Middle)?">
          Атака, при которой злоумышленник встраивается между жертвой и легитимным сервисом, перехватывая и
          потенциально изменяя трафик между ними, оставаясь незамеченным для обеих сторон — часто происходит в
          незащищённых публичных Wi-Fi сетях.
        </QA>

        <TheoryExample title="Совет по подготовке">
          На собеседовании по кибербезопасности часто просят не просто дать определение атаки, а объяснить, как от
          неё защититься на практике. К каждому виду атаки в этом списке держи в голове хотя бы одну конкретную
          меру защиты.
        </TheoryExample>
      </section>

      <section className="theory-section">
        <Section title="Часть 2. Защита, шифрование и пентест" />

        <QA n={13} q="В чём разница между симметричным и асимметричным шифрованием?">
          Симметричное шифрование использует один и тот же ключ и для шифрования, и для расшифровки — быстрее, но
          требует безопасно передать ключ обеим сторонам заранее. Асимметричное использует пару ключей — открытый
          (для шифрования) и закрытый (для расшифровки) — не требует предварительного обмена секретом, но работает
          медленнее.
        </QA>

        <QA n={14} q="Чем хеширование отличается от шифрования?">
          Шифрование обратимо: зашифрованные данные можно расшифровать обратно исходным ключом. Хеширование
          необратимо: из хеша нельзя восстановить исходные данные, оно используется для проверки целостности и
          безопасного хранения паролей, а не для последующего восстановления исходного значения.
        </QA>

        <QA n={15} q="Зачем нужна соль (salt) при хешировании паролей?">
          Соль — случайная строка, добавляемая к паролю перед хешированием. Она гарантирует, что одинаковые пароли
          у разных пользователей дают разные хеши, что защищает от атак по заранее посчитанным таблицам хешей
          (rainbow tables) и делает подбор паролей значительно дороже для атакующего.
        </QA>

        <QA n={16} q="Что такое двухфакторная аутентификация (2FA)?">
          Дополнительный уровень защиты входа в аккаунт: помимо пароля (то, что пользователь знает) требуется
          второй фактор — например, код из приложения или SMS (то, что у пользователя есть). Даже если пароль
          украден, без второго фактора войти в аккаунт не получится.
        </QA>

        <QA n={17} q="Что такое межсетевой экран (firewall)?">
          Система (программная или аппаратная), которая контролирует сетевой трафик между разными сегментами сети
          (например, между интернетом и внутренней сетью компании) по заданным правилам, разрешая или блокируя
          соединения на основе адресов, портов и протоколов.
        </QA>

        <QA n={18} q="Что такое VPN и как он защищает пользователя?">
          Virtual Private Network — технология, создающая зашифрованный туннель между устройством пользователя и
          VPN-сервером. Весь трафик внутри туннеля шифруется, что защищает от перехвата в незащищённых сетях
          (например, публичном Wi-Fi) и скрывает реальный IP-адрес пользователя от конечного сайта.
        </QA>

        <QA n={19} q="В чём разница между IDS и IPS?">
          IDS (Intrusion Detection System) обнаруживает подозрительную активность в сети и оповещает
          администратора, но сама не блокирует её. IPS (Intrusion Prevention System) не только обнаруживает, но и
          автоматически блокирует подозрительный трафик в реальном времени.
        </QA>

        <QA n={20} q="Что такое принцип наименьших привилегий (least privilege)?">
          Правило, по которому пользователю, программе или процессу дают только тот минимальный набор прав
          доступа, который необходим для выполнения их задачи — не больше. Снижает ущерб в случае компрометации
          учётной записи или программы.
        </QA>

        <QA n={21} q="Что такое OWASP Top 10?">
          Регулярно обновляемый список десяти самых критичных категорий уязвимостей веб-приложений, составляемый
          сообществом OWASP (Open Worldwide Application Security Project) — используется как ориентир при
          проверке безопасности веб-приложений (в него входят, например, инъекции, некорректный контроль доступа,
          неправильная конфигурация безопасности).
        </QA>

        <QA n={22} q="Что такое пентест (penetration testing)?">
          Санкционированная имитация реальной атаки на систему, проводимая специалистом (пентестером) с
          разрешения владельца системы, чтобы найти уязвимости раньше настоящих злоумышленников и дать
          рекомендации по их устранению.
        </QA>

        <QA n={23} q="Что такое SIEM-система?">
          Security Information and Event Management — система, которая собирает логи и события безопасности со
          всей инфраструктуры компании в одном месте, автоматически коррелирует их и помогает быстро обнаруживать
          подозрительные паттерны, которые были бы незаметны при просмотре логов каждой системы по отдельности.
        </QA>

        <QA n={24} q="Как объяснить руководству, зачем компании нужна кибербезопасность?">
          Через риски и деньги, а не термины: утечка данных клиентов ведёт к штрафам и потере доверия, простой
          из-за атаки — к прямым финансовым потерям, а инвестиции в базовую защиту (обновления, резервные копии,
          обучение сотрудников) обычно многократно дешевле, чем последствия одного успешного инцидента.
        </QA>
      </section>
    </div>
  )
}
